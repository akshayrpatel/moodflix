package com.moodflix.interactions.model;

import jakarta.persistence.*;
import lombok.*;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import java.util.UUID;

/**
 * Represents a user profile entity mapped to PostgreSQL {@code users} table.
 * <p>
 * This entity models the persistent user state, specifically the 384-dimensional
 * semantic taste vector and the optimistic locking version counter.
 * </p>
 *
 * <h2>Concurrency & Locking:</h2>
 * <ul>
 *   <li><b>Optimistic Concurrency Control:</b> The {@link #version} field is annotated with
 *       {@link Version}. Hibernate appends {@code WHERE version = ?} to every SQL UPDATE.
 *       If an out-of-band process (e.g. Gateway onboarding quiz or profile update) modifies
 *       the row simultaneously, an {@link jakarta.persistence.OptimisticLockException} is thrown,
 *       preventing lost-update anomalies.</li>
 *   <li><b>Vector Mapping:</b> {@link #tasteVector} is stored as PostgreSQL {@code real[]}
 *       and cast to {@code vector(384)} for pgvector cosine-distance similarity searches.</li>
 * </ul>
 */
@Entity
@Table(name = "users")
@Getter
@Setter
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class User {

    /**
     * Unique identifier for the user (UUID v4).
     */
    @Id
    private UUID id;

    @Column(nullable = false, unique = true)
    private String email;

    private String username;

    @Column(name = "password_hash", nullable = false)
    private String passwordHash;

    /**
     * 384-dimensional dense semantic embedding generated by all-MiniLM-L6-v2.
     * Represents the user's aggregated viewing preferences in emotional space.
     */
    @Column(name = "taste_vector", columnDefinition = "real[]")
    @JdbcTypeCode(SqlTypes.ARRAY)
    private float[] tasteVector;

    /**
     * Optimistic locking version counter.
     * Incremented automatically by Hibernate on every successful persist/update.
     */
    @Version
    @Column(nullable = false)
    private Long version;
}